/**
 * Writes prompts/EXPORTED_PROMPT.md: everything that drives the agent's behavior, generated
 * from the code that actually runs (system prompt, tool definitions, per-turn context format).
 * Usage: pnpm export:prompt
 */
import { readFileSync, writeFileSync } from "node:fs";
import { buildContextMessage, SYSTEM_PROMPT } from "../src/agent/context";
import { MODEL } from "../src/agent/loop";
import { buildTools } from "../src/agent/tools";
import { catalogFromSource } from "../src/lib/restaurants/catalog";
import { parseRestaurantFile } from "../src/lib/restaurants/parse-source";

const catalog = catalogFromSource(parseRestaurantFile(readFileSync("data/restaurants.txt", "utf8")));

const exampleContext = buildContextMessage(
  new Date("2026-10-16T02:30:00Z"),
  [
    { key: "diet", value: "vegetarian", scope: "user" },
    { key: "party_size", value: "4 people", scope: "conversation" },
  ],
  [{ restaurantId: 21, name: "Casa Verde", status: "rejected" }],
  ["poll 3f1c...: Mangal Grill (id 14): 2, Zaytoon Grill (id 31): 1"],
);

const document = `# Nearby agent: exported prompt

Generated by \`pnpm export:prompt\` from the code that runs in production. Do not edit by hand;
the sources are \`prompts/system-prompt.md\`, \`src/agent/tools.ts\`, and \`src/agent/context.ts\`.

Model: \`${MODEL}\` at low effort, adaptive thinking, up to 8 model calls per user message.

## How a request is assembled

1. **System prompt** (below), identical every turn so it stays cached.
2. **Transcript**: the last 30 visible user and assistant messages of this conversation, from the
   database. Before each past reply, a short system note lists that turn's tool calls (from
   \`agent_events\`), so the model remembers what it did, not just what it said.
3. **Current context**: a mid-conversation system message right after the newest user message,
   rebuilt every turn from the database (example below).
4. **Tools**: the definitions below, with strict schemas. Inputs are also validated with Zod
   before running, and every call is logged to \`agent_events\`.

## 1. System prompt (verbatim)

\`\`\`\`markdown
${SYSTEM_PROMPT.trim()}
\`\`\`\`

## 2. Per-turn "Current context" message (example)

\`\`\`
${exampleContext}
\`\`\`

## 3. Tool definitions (as sent to the API)

${buildTools(catalog)
  .definitions.map((tool) => `### \`${tool.name}\`\n\n${tool.description}\n\n\`\`\`json\n${JSON.stringify(tool.input_schema, null, 2)}\n\`\`\``)
  .join("\n\n")}
`;

writeFileSync("prompts/EXPORTED_PROMPT.md", document);
console.log("Wrote prompts/EXPORTED_PROMPT.md");
